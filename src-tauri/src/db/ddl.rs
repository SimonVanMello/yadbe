//! DDL text rebuilt from the catalog, for the objects an engine keeps no definition of
//! (F-024): tables on PostgreSQL and SQL Server, sequences, types, indexes the catalog lists
//! without their statement. Every reconstructed text opens with a comment that says so.
//! Identifiers are quoted through the dialect.

use crate::db::dialect::Dialect;
use crate::db::meta::qualified_name;
use crate::db::meta::{
    ColumnInfo, ForeignKey, ForeignKeyAction, Identity, IndexInfo, ObjectDetail, ObjectInfo,
    ObjectKind, ObjectRef, SequenceSummary, TableDetails, TypeCategory, TypeSummary,
};
use crate::db::object_ops::{GeneratedStyle, IdentityStyle};
use crate::db::split::Separator;

fn header(dialect: &dyn Dialect, what: &str) -> String {
    let mut text = format!(
        "-- Reconstructed by yadbe from the catalog: {} keeps no definition text for {what}.\n",
        dialect.label()
    );
    if let Some(note) = dialect.ddl_style().note {
        text.push_str("-- ");
        text.push_str(note);
        text.push('\n');
    }
    text
}

fn string_literal(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

fn action(keyword: &str, action: ForeignKeyAction) -> Option<String> {
    let text = match action {
        ForeignKeyAction::NoAction => return None,
        ForeignKeyAction::Restrict => "RESTRICT",
        ForeignKeyAction::Cascade => "CASCADE",
        ForeignKeyAction::SetNull => "SET NULL",
        ForeignKeyAction::SetDefault => "SET DEFAULT",
    };
    Some(format!("{keyword} {text}"))
}

fn column_list(dialect: &dyn Dialect, columns: &[String]) -> String {
    columns
        .iter()
        .map(|c| dialect.quote_identifier(c))
        .collect::<Vec<_>>()
        .join(", ")
}

/// A column's type with its schema when it is one of the schema's own types (`type_name` is
/// the bare name where the engine prints only that): the text runs from any default schema.
fn column_type(dialect: &dyn Dialect, column: &ColumnInfo, user_types: &[ObjectRef]) -> String {
    user_types
        .iter()
        .find(|t| t.name == column.type_name)
        .map_or_else(|| column.type_name.clone(), |t| qualified_name(dialect, t))
}

fn column_line(dialect: &dyn Dialect, column: &ColumnInfo, user_types: &[ObjectRef]) -> String {
    let style = dialect.ddl_style();
    let name = dialect.quote_identifier(&column.name);
    if let Some(generated) = &column.generated {
        let expression = generated.expression.as_deref().unwrap_or("NULL");
        return match style.generated {
            GeneratedStyle::Computed => format!(
                "{name} AS {expression}{}",
                if generated.stored { " PERSISTED" } else { "" }
            ),
            GeneratedStyle::Standard => format!(
                "{name} {} GENERATED ALWAYS AS ({expression}) {}",
                column_type(dialect, column, user_types),
                if generated.stored {
                    "STORED"
                } else {
                    "VIRTUAL"
                }
            ),
        };
    }
    let mut line = format!("{name} {}", column_type(dialect, column, user_types));
    match (column.identity, style.identity) {
        (Some(Identity::Always), IdentityStyle::GeneratedAsIdentity) => {
            line.push_str(" GENERATED ALWAYS AS IDENTITY");
        }
        (Some(Identity::ByDefault), IdentityStyle::GeneratedAsIdentity) => {
            line.push_str(" GENERATED BY DEFAULT AS IDENTITY");
        }
        (Some(_), IdentityStyle::Identity) => line.push_str(" IDENTITY(1,1)"),
        (Some(_), IdentityStyle::AutoIncrement) => line.push_str(" AUTO_INCREMENT"),
        _ => {}
    }
    if let Some(default) = &column.default {
        line.push_str(" DEFAULT ");
        line.push_str(default);
    }
    if !column.nullable {
        line.push_str(" NOT NULL");
    }
    line
}

fn constraint(name: Option<&String>, dialect: &dyn Dialect, body: String) -> String {
    match name {
        Some(name) => format!("CONSTRAINT {} {body}", dialect.quote_identifier(name)),
        None => body,
    }
}

fn foreign_key_line(dialect: &dyn Dialect, fk: &ForeignKey) -> String {
    let mut body = format!(
        "FOREIGN KEY ({}) REFERENCES {} ({})",
        column_list(dialect, &fk.columns),
        qualified_name(dialect, &fk.referenced_table),
        column_list(dialect, &fk.referenced_columns)
    );
    for clause in [
        action("ON DELETE", fk.on_delete),
        action("ON UPDATE", fk.on_update),
    ]
    .into_iter()
    .flatten()
    {
        body.push(' ');
        body.push_str(&clause);
    }
    if fk.deferrable {
        body.push_str(" DEFERRABLE");
    }
    constraint(fk.name.as_ref(), dialect, body)
}

/// A `CREATE INDEX` rebuilt from the columns the catalog lists.
pub fn index_ddl(dialect: &dyn Dialect, table: &ObjectRef, index: &IndexInfo) -> String {
    // A key is a column, written `name` or `name DESC`, unless the engine indexes expressions:
    // then the text is the engine's own.
    let keys: Vec<String> = index
        .columns
        .iter()
        .map(|key| {
            if dialect.meta_capabilities().expression_indexes {
                return key.clone();
            }
            match key.strip_suffix(" DESC") {
                Some(name) => format!("{} DESC", dialect.quote_identifier(name)),
                None => dialect.quote_identifier(key),
            }
        })
        .collect();
    let mut sql = format!(
        "CREATE {}INDEX {} ON {} ({})",
        if index.unique { "UNIQUE " } else { "" },
        dialect.quote_identifier(&index.name),
        qualified_name(dialect, table),
        keys.join(", ")
    );
    if let Some(predicate) = &index.predicate {
        sql.push_str(" WHERE ");
        sql.push_str(predicate);
    }
    sql.push(';');
    sql
}

/// A statement as a script written to be run again holds it: ended with `;`, or, on an engine
/// whose statements may hold `;` in their body (MySQL), wrapped in a `DELIMITER` block.
pub fn script_statement(dialect: &dyn Dialect, statement: &str) -> String {
    let body = statement.trim().trim_end_matches(';').trim_end();
    match dialect.syntax().separator {
        Separator::MysqlDelimiter if body.contains(';') => {
            format!("DELIMITER //\n{body}\n//\nDELIMITER ;")
        }
        _ => format!("{body};"),
    }
}

/// The indexes (unless `include_indexes` is off: the engine's own text holds them) and the
/// triggers a table's text is followed by, one statement each, left out when `existing`
/// already has them.
pub fn table_extras(
    dialect: &dyn Dialect,
    details: &TableDetails,
    existing: &str,
    include_indexes: bool,
) -> String {
    let backing: Vec<&String> = details
        .unique_keys
        .iter()
        .filter_map(|key| key.name.as_ref())
        .collect();
    let mut out = String::new();
    for index in &details.indexes {
        if !include_indexes || index.primary || backing.contains(&&index.name) {
            continue;
        }
        let statement = index
            .definition
            .clone()
            .unwrap_or_else(|| index_ddl(dialect, &details.table, index));
        if !existing.contains(statement.trim_end_matches(';')) {
            out.push('\n');
            out.push_str(&script_statement(dialect, &statement));
            out.push('\n');
        }
    }
    for trigger in &details.triggers {
        if let Some(definition) = &trigger.definition
            && !existing.contains(definition.trim())
        {
            out.push('\n');
            // `CREATE TRIGGER` must start its batch on SQL Server.
            if dialect.syntax().separator == Separator::GoBatches {
                out.push_str("GO\n");
            }
            out.push_str(&script_statement(dialect, definition));
            out.push('\n');
        }
    }
    out
}

/// `CREATE TABLE` with its columns and constraints, then its indexes and triggers.
/// `user_types`: the types of the table's schema.
pub fn table_ddl(
    dialect: &dyn Dialect,
    details: &TableDetails,
    user_types: &[ObjectRef],
) -> String {
    let mut lines: Vec<String> = details
        .columns
        .iter()
        .map(|c| format!("  {}", column_line(dialect, c, user_types)))
        .collect();
    if let Some(pk) = &details.primary_key {
        lines.push(format!(
            "  {}",
            constraint(
                pk.name.as_ref(),
                dialect,
                format!("PRIMARY KEY ({})", column_list(dialect, &pk.columns))
            )
        ));
    }
    for key in &details.unique_keys {
        lines.push(format!(
            "  {}",
            constraint(
                key.name.as_ref(),
                dialect,
                format!("UNIQUE ({})", column_list(dialect, &key.columns))
            )
        ));
    }
    for fk in &details.foreign_keys {
        lines.push(format!("  {}", foreign_key_line(dialect, fk)));
    }
    for check in &details.checks {
        lines.push(format!(
            "  {}",
            constraint(
                check.name.as_ref(),
                dialect,
                format!("CHECK ({})", check.expression)
            )
        ));
    }
    let mut text = header(dialect, "a table");
    text.push_str(&format!(
        "CREATE TABLE {} (\n{}\n);\n",
        qualified_name(dialect, &details.table),
        lines.join(",\n")
    ));
    let extras = table_extras(dialect, details, &text, true);
    text.push_str(&extras);
    text
}

fn sequence_ddl(dialect: &dyn Dialect, object: &ObjectRef, s: &SequenceSummary) -> String {
    let mut text = header(dialect, "a sequence");
    text.push_str(&format!(
        "CREATE SEQUENCE {}\n  AS {}\n  START WITH {}\n  INCREMENT BY {}\n  MINVALUE {}\n  MAXVALUE {}\n  {};\n",
        qualified_name(dialect, object),
        s.data_type,
        s.start,
        s.increment,
        s.min,
        s.max,
        if s.cycle { "CYCLE" } else { "NO CYCLE" }
    ));
    if let Some(owner) = &s.owned_by {
        text.push_str(&format!(
            "\nALTER SEQUENCE {} OWNED BY {}.{};\n",
            qualified_name(dialect, object),
            qualified_name(dialect, &owner.table),
            dialect.quote_identifier(&owner.column)
        ));
    }
    text
}

fn type_ddl(dialect: &dyn Dialect, object: &ObjectRef, t: &TypeSummary) -> String {
    let name = qualified_name(dialect, object);
    let mut text = header(dialect, "a type");
    match t.category {
        TypeCategory::Enum => {
            let labels: Vec<String> = t.enum_values.iter().map(|v| string_literal(v)).collect();
            text.push_str(&format!(
                "CREATE TYPE {name} AS ENUM ({});\n",
                labels.join(", ")
            ));
        }
        TypeCategory::Composite => {
            let attributes: Vec<String> = t
                .attributes
                .iter()
                .map(|a| format!("  {} {}", dialect.quote_identifier(&a.name), a.type_name))
                .collect();
            // A user-defined table type (SQL Server) says `AS TABLE`.
            let table = if dialect.ddl_style().generated == GeneratedStyle::Computed {
                "TABLE "
            } else {
                ""
            };
            text.push_str(&format!(
                "CREATE TYPE {name} AS {table}(\n{}\n);\n",
                attributes.join(",\n")
            ));
        }
        TypeCategory::Domain => {
            let base = t.base_type.as_deref().unwrap_or("unknown");
            if dialect.ddl_style().generated == GeneratedStyle::Computed {
                text.push_str(&format!("CREATE TYPE {name} FROM {base};\n"));
            } else {
                text.push_str(&format!("CREATE DOMAIN {name} AS {base};\n"));
            }
        }
        TypeCategory::Range => {
            let base = t.base_type.as_deref().unwrap_or("unknown");
            text.push_str(&format!(
                "CREATE TYPE {name} AS RANGE (SUBTYPE = {base});\n"
            ));
        }
        TypeCategory::Base => {
            text.push_str(&format!(
                "-- {name} is a base type: it is defined by a library, not by SQL.\n"
            ));
        }
    }
    text
}

/// Sequences and types, from their entry of the objects list; `None` for the other kinds.
pub fn object_ddl(dialect: &dyn Dialect, object: &ObjectRef, info: &ObjectInfo) -> Option<String> {
    match (&info.kind, &info.detail) {
        (ObjectKind::Sequence, ObjectDetail::Sequence(s)) => Some(sequence_ddl(dialect, object, s)),
        (ObjectKind::Type, ObjectDetail::Type(t)) => Some(type_ddl(dialect, object, t)),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::db::dialect::Engine;
    use crate::db::meta::{CheckConstraint, Generated, KeyConstraint};
    use crate::db::value::ValueKind;

    fn column(name: &str, type_name: &str, nullable: bool) -> ColumnInfo {
        ColumnInfo {
            name: name.into(),
            ordinal: 1,
            type_name: type_name.into(),
            kind: ValueKind::Other,
            nullable,
            default: None,
            identity: None,
            generated: None,
            comment: None,
            primary_key: false,
            foreign_key: false,
        }
    }

    fn orders(schema: Option<&str>) -> TableDetails {
        let mut id = column("id", "integer", false);
        id.identity = Some(Identity::Always);
        let mut total = column("total", "numeric(12,2)", true);
        total.generated = Some(Generated {
            stored: true,
            expression: Some("(a + b)".into()),
        });
        let mut note = column("note", "text", true);
        note.default = Some("''::text".into());
        TableDetails {
            table: ObjectRef {
                database: "shop".into(),
                schema: schema.map(str::to_owned),
                name: "orders".into(),
            },
            kind: ObjectKind::Table,
            comment: None,
            row_estimate: None,
            columns: vec![id, total, note],
            primary_key: Some(KeyConstraint {
                name: Some("orders_pkey".into()),
                columns: vec!["id".into()],
            }),
            unique_keys: Vec::new(),
            foreign_keys: Vec::new(),
            checks: vec![CheckConstraint {
                name: Some("pos".into()),
                expression: "total >= 0".into(),
            }],
            indexes: vec![
                IndexInfo {
                    name: "orders_pkey".into(),
                    columns: vec!["id".into()],
                    unique: true,
                    primary: true,
                    method: None,
                    predicate: None,
                    definition: None,
                },
                IndexInfo {
                    name: "orders_note_idx".into(),
                    columns: vec!["note".into()],
                    unique: false,
                    primary: false,
                    method: None,
                    predicate: Some("note IS NOT NULL".into()),
                    definition: None,
                },
            ],
            triggers: Vec::new(),
        }
    }

    #[test]
    fn rebuilds_a_postgres_table() {
        let sql = table_ddl(Engine::Postgres.dialect(), &orders(Some("sales")), &[]);
        assert!(sql.starts_with("-- Reconstructed by yadbe"), "{sql}");
        assert!(sql.contains("CREATE TABLE \"sales\".\"orders\" ("), "{sql}");
        assert!(sql.contains("\"id\" integer GENERATED ALWAYS AS IDENTITY NOT NULL"));
        assert!(sql.contains("\"total\" numeric(12,2) GENERATED ALWAYS AS ((a + b)) STORED"));
        assert!(sql.contains("\"note\" text DEFAULT ''::text"));
        assert!(sql.contains("CONSTRAINT \"orders_pkey\" PRIMARY KEY (\"id\")"));
        assert!(sql.contains("CONSTRAINT \"pos\" CHECK (total >= 0)"));
        assert!(sql.contains(
            "CREATE INDEX \"orders_note_idx\" ON \"sales\".\"orders\" (note) WHERE note IS NOT NULL;"
        ));
        assert_eq!(
            sql.matches("CREATE INDEX").count(),
            1,
            "the key's index is implied"
        );
    }

    #[test]
    fn rebuilds_a_sql_server_table_with_a_note() {
        let sql = table_ddl(Engine::Mssql.dialect(), &orders(Some("dbo")), &[]);
        assert!(sql.contains("IDENTITY(1,1)"), "{sql}");
        assert!(sql.contains("[total] AS (a + b) PERSISTED"), "{sql}");
        assert!(sql.contains("CREATE TABLE [dbo].[orders] ("), "{sql}");
        assert!(sql.contains("seed and increment"), "{sql}");
    }

    #[test]
    fn writes_sequences_and_enums() {
        let object = ObjectRef {
            database: "shop".into(),
            schema: Some("sales".into()),
            name: "invoice_seq".into(),
        };
        let seq = SequenceSummary {
            data_type: "bigint".into(),
            start: "1000".into(),
            increment: "1".into(),
            min: "1".into(),
            max: "9223372036854775807".into(),
            cycle: false,
            owned_by: None,
        };
        let sql = sequence_ddl(Engine::Postgres.dialect(), &object, &seq);
        assert!(
            sql.contains("CREATE SEQUENCE \"sales\".\"invoice_seq\""),
            "{sql}"
        );
        assert!(
            sql.contains("START WITH 1000") && sql.contains("NO CYCLE"),
            "{sql}"
        );
        let status = TypeSummary {
            category: TypeCategory::Enum,
            enum_values: vec!["it's".into(), "ok".into()],
            base_type: None,
            attributes: Vec::new(),
        };
        let sql = type_ddl(Engine::Postgres.dialect(), &object, &status);
        assert!(sql.contains("AS ENUM ('it''s', 'ok')"), "{sql}");
    }
}
