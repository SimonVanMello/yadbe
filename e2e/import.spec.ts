import { expect, test, type Locator, type Page } from '@playwright/test';

/**
 * Imports (M3-10) on the mock backend: the data import wizard (file, columns, dry run, import,
 * read-only refusal) and the connection import / export dialogs. Captures in both themes.
 */

interface MockControls {
  setLatency(ms: number): void;
  setTableDataLatency(ms: number): void;
  setImportTick(ms: number): void;
  getFile(path: string): string | undefined;
}
type MockWindow = Window & { __yadbeMock?: MockControls };

const THEMES = [
  { name: 'graphite', colorScheme: 'dark' },
  { name: 'paper', colorScheme: 'light' },
] as const;

async function capture(page: Page, theme: string, state: string) {
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({
    path: test.info().outputPath(`import-${state}-${theme}.png`),
    animations: 'disabled',
  });
}

const tree = (page: Page) => page.getByRole('tree', { name: 'Connections' });
const item = (page: Page, name: string | RegExp) => tree(page).getByRole('treeitem', { name });
const grid = (page: Page) => page.getByRole('grid', { name: /^Rows of / });
const wizard = (page: Page) => page.getByRole('dialog', { name: /^Import data into / });

const ORDERS_CSV = `customer_id,status,subtotal,shipping,total,note
12,paid,129.90,5.00,134.90,first order
13,pending,abc,0,0,bad subtotal
14,shipped,18.00,0,18.00,
`;

async function expand(row: Locator) {
  await expect(row).toBeVisible();
  if ((await row.getAttribute('aria-expanded')) === 'false') {
    await row.locator('span').first().click();
  }
  await expect(row).toHaveAttribute('aria-expanded', 'true');
}

async function openOrders(page: Page, connection: RegExp) {
  await item(page, connection).dblclick();
  await expect(item(page, connection)).toHaveAccessibleName(/Connected/);
  await expect(item(page, /^public$/).first()).toBeVisible();
  await expand(item(page, /^shop$/).last());
  await expand(item(page, /^Tables \(/).last());
  await item(page, /^orders$/).dblclick();
  await expect(grid(page)).toBeVisible();
}

async function chooseFile(page: Page, name: string, text: string) {
  const chooser = page.waitForEvent('filechooser');
  await wizard(page)
    .getByRole('button', { name: /Choose a file…|Change…/ })
    .click();
  await (await chooser).setFiles({ name, mimeType: 'text/csv', buffer: Buffer.from(text) });
}

for (const { name, colorScheme } of THEMES) {
  test.describe(`${name} theme`, () => {
    test.use({ colorScheme, locale: 'en-US' });

    test.beforeEach(async ({ page }) => {
      await page.goto('/');
      await expect(page.locator('html')).toHaveAttribute('data-theme', name);
      await expect(item(page, /^local postgres,/)).toBeVisible();
      await page.evaluate(() => {
        (window as MockWindow).__yadbeMock?.setLatency(30);
        (window as MockWindow).__yadbeMock?.setTableDataLatency(0);
        (window as MockWindow).__yadbeMock?.setImportTick(0);
      });
    });

    test('the wizard maps columns, checks types, dry-runs and imports', async ({ page }) => {
      await openOrders(page, /^local postgres,/);
      await page.getByRole('button', { name: 'Import data into the table…' }).click();
      await expect(wizard(page)).toBeVisible();
      await expect(wizard(page).getByTestId('import-file')).toContainText('No file chosen');
      await capture(page, name, 'wizard-empty');

      await chooseFile(page, 'orders.csv', ORDERS_CSV);
      await expect(wizard(page).getByTestId('import-file')).toContainText('orders.csv');
      await expect(wizard(page).getByLabel('Delimiter')).toHaveValue('comma');
      const preview = wizard(page).getByRole('region', { name: /^First 3 rows/ });
      await expect(preview).toContainText('customer_id');
      await expect(preview).toContainText('129.90');
      await capture(page, name, 'file');

      // Another delimiter re-reads the file: one column, no match, a warning-free preview.
      await wizard(page).getByLabel('Delimiter').selectOption('semicolon');
      await expect(preview.getByRole('columnheader')).toHaveCount(1);
      await wizard(page).getByLabel('Delimiter').selectOption('comma');
      await expect(preview.getByRole('columnheader')).toHaveCount(6);

      await wizard(page).getByRole('button', { name: 'Next' }).click();
      const map = (column: string) => wizard(page).getByTestId(`map-${column}`);
      await expect(map('customer_id').getByRole('combobox')).toHaveValue('file:0');
      await expect(map('subtotal').getByRole('combobox')).toHaveValue('file:2');
      await expect(map('id')).toContainText('Generated by the server');
      await expect(map('total')).toContainText('Computed column');
      await expect(map('subtotal')).toContainText('One value will not convert');
      await expect(map('subtotal')).toContainText('abc');
      await expect(wizard(page).getByRole('button', { name: 'Next' })).toBeEnabled();
      await capture(page, name, 'columns');

      // A required column left out blocks the next step and says which.
      await map('customer_id').getByRole('combobox').selectOption('skip');
      await expect(wizard(page).getByRole('alert')).toContainText('customer_id');
      await expect(wizard(page).getByRole('button', { name: 'Next' })).toBeDisabled();
      await capture(page, name, 'columns-missing');
      await map('customer_id').getByRole('combobox').selectOption('file:0');
      await map('note').getByRole('combobox').selectOption('constant');
      await map('note').getByLabel('Constant for note').fill('imported');

      await wizard(page).getByRole('button', { name: 'Next' }).click();
      await expect(
        wizard(page).getByRole('radio', { name: 'Skip it and report it' }),
      ).toBeChecked();
      await expect(wizard(page).getByRole('radio', { name: /One transaction/ })).toBeChecked();
      await capture(page, name, 'run');

      await wizard(page).getByRole('button', { name: 'Dry run' }).click();
      const result = wizard(page).getByTestId('import-result');
      await expect(result).toContainText('Dry run: 2 rows would be written and 1 rejected');
      await expect(result).toContainText('Nothing was changed');
      await expect(result.getByRole('region', { name: 'Rejected rows' })).toContainText('abc');
      await capture(page, name, 'dry-run');

      await wizard(page).getByRole('button', { name: 'Import', exact: true }).click();
      await expect(result).toContainText('Imported 2 rows');
      await expect(result).toContainText('1 row rejected');
      await capture(page, name, 'done');
      await wizard(page).getByRole('button', { name: 'Close' }).click();
      await expect(wizard(page)).toBeHidden();
      // Table tabs showing the table are told their rows are old.
      await expect(page.getByText('Changed elsewhere: refresh to see it.')).toBeVisible();
    });

    test('stopping at the first bad row rolls the import back and says where', async ({ page }) => {
      await openOrders(page, /^local postgres,/);
      await page.getByRole('button', { name: 'Import data into the table…' }).click();
      await chooseFile(page, 'orders.csv', ORDERS_CSV);
      await wizard(page).getByRole('button', { name: 'Next' }).click();
      await wizard(page).getByRole('button', { name: 'Next' }).click();
      await wizard(page).getByRole('radio', { name: 'Stop at the first error' }).click();
      await wizard(page).getByRole('radio', { name: 'Commit every batch' }).click();
      await expect(wizard(page)).toContainText('already written stay in the table');
      await wizard(page)
        .getByRole('radio', { name: /One transaction/ })
        .click();
      await wizard(page).getByRole('button', { name: 'Import', exact: true }).click();
      const result = wizard(page).getByTestId('import-result');
      await expect(result).toContainText('The import failed');
      await expect(result).toContainText('stopped at line 3');
      await expect(result).toContainText('Nothing was kept: the transaction was rolled back');
      await capture(page, name, 'failed');
    });

    test('a read-only connection cannot be imported into', async ({ page }) => {
      await openOrders(page, /^shop · prod,/);
      await page.getByRole('button', { name: 'Import data into the table…' }).click();
      await chooseFile(page, 'orders.csv', ORDERS_CSV);
      await wizard(page).getByRole('button', { name: 'Next' }).click();
      await expect(wizard(page).getByRole('alert').first()).toContainText('read-only');
      await expect(wizard(page).getByRole('button', { name: 'Next' })).toBeDisabled();
      await capture(page, name, 'read-only');
    });

    test('connections are imported from another tool with their folders', async ({ page }) => {
      await page.getByRole('button', { name: 'Import or export connections' }).click();
      await page.getByRole('menuitem', { name: 'Import connections…' }).click();
      const dialog = page.getByRole('dialog', { name: 'Import connections' });
      await expect(dialog).toBeVisible();
      await expect(dialog.getByTestId('connimport-file')).toContainText('azuredatastudio');
      const found = dialog.getByRole('group', { name: 'Found connections' });
      await expect(found.getByText('Orders (prod)')).toBeVisible();
      await expect(found).toContainText('Already saved as “reporting”');
      await expect(found).toContainText('Windows integrated authentication is not supported yet');
      await expect(dialog).toContainText('Kusto cluster');
      // Only what does not exist yet is ticked.
      await expect(found.getByRole('checkbox', { name: /Orders \(prod\)/ })).toBeChecked();
      await expect(found.getByRole('checkbox', { name: /reporting \(copy\)/ })).not.toBeChecked();
      await capture(page, name, 'connections');

      await dialog.getByRole('button', { name: 'Import 2 connections' }).click();
      await expect(page.getByText('Imported 2 connections', { exact: true })).toBeVisible();
      await expect(dialog).toBeHidden();
      await expect(item(page, /^Prod \d+$/)).toBeVisible();
      await expand(item(page, /^Prod \d+$/));
      await expect(item(page, /^EU \d+$/)).toBeVisible();
      await capture(page, name, 'connections-imported');
    });

    test('a pgpass file offers its passwords for the keychain', async ({ page }) => {
      await page.getByRole('button', { name: 'Import or export connections' }).click();
      await page.getByRole('menuitem', { name: 'Import connections…' }).click();
      const dialog = page.getByRole('dialog', { name: 'Import connections' });
      await dialog.getByLabel('Import from').selectOption('pgpass');
      const found = dialog.getByRole('group', { name: 'Found connections' });
      await expect(found).toContainText('analyst@warehouse.example.com:5433/dw');
      await expect(found).toContainText('Already saved as “local postgres”');
      const passwords = dialog.getByRole('switch', { name: /Import the passwords/ });
      // The entry that does not exist yet is ticked and holds a password.
      await expect(found.getByRole('checkbox', { name: /analyst@warehouse/ })).toBeChecked();
      await expect(passwords).toBeEnabled();
      await found.getByRole('checkbox', { name: /analyst@warehouse/ }).uncheck();
      await expect(passwords).toBeDisabled();
      await found.getByRole('checkbox', { name: /analyst@warehouse/ }).check();
      await expect(passwords).toBeEnabled();
      await passwords.click();
      await capture(page, name, 'pgpass');
      await dialog.getByRole('button', { name: /^Import \d+ connections?$/ }).click();
      await expect(page.getByText(/^Imported \d+ connections?$/)).toBeVisible();
      await expect(page.getByText(/1 passwords in the keychain/).first()).toBeVisible();
    });

    test('connections are exported without secrets', async ({ page }) => {
      await page.getByRole('button', { name: 'Import or export connections' }).click();
      await page.getByRole('menuitem', { name: 'Export connections…' }).click();
      const dialog = page.getByRole('dialog', { name: 'Export connections' });
      await expect(dialog).toContainText('never holds a password');
      await expect(dialog.getByRole('checkbox', { name: /local postgres/ })).toBeChecked();
      await dialog.getByRole('checkbox', { name: /auth failure demo/ }).uncheck();
      await capture(page, name, 'export');
      await dialog.getByRole('button', { name: /^Export \d+ connections…$/ }).click();
      await expect(page.getByText(/^Exported \d+ connections$/)).toBeVisible();
      const file = await page.evaluate(() =>
        (window as MockWindow).__yadbeMock?.getFile('/home/ana/exports/yadbe-connections.json'),
      );
      expect(file).toContain('"format": "yadbe-connections"');
      expect(file).toContain('local postgres');
      expect(file).not.toContain('auth failure demo');
      expect(file?.toLowerCase()).not.toContain('"password":');
    });
  });
}
